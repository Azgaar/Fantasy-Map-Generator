/**
 * worker-protocol.ts — the message contract between the page and the compile worker.
 *
 * Shared by both sides on purpose: the worker script and the page's client are
 * built from the same file, so a protocol change cannot be half-applied.
 *
 * The worker is not a separate bundle. It is a Blob whose only statement is
 * `import("<the mod's own URL>")`, which is why this file must stay free of DOM
 * assumptions: inside the worker, `document` does not exist.
 */

import type { MapPack } from "../common/types";
import { compileAzgaar } from "../compiler/index";
import { azgaarMapFromSnapshot, type FmgWorldSnapshot } from "./from-fmg";

export interface CompileRequest {
  id: number;
  type: "compile";
  snapshot: FmgWorldSnapshot;
}

export interface CompileResponse {
  id: number;
  ok: boolean;
  pack?: MapPack;
  contentHash?: string;
  elapsedMs?: number;
  error?: string;
}

/** Compile a snapshot. Pure — this is what runs inside the Worker. */
export function compileSnapshot(snapshot: FmgWorldSnapshot): { pack: MapPack; contentHash: string; elapsedMs: number } {
  const started = performance.now();
  const { pack, contentHash } = compileAzgaar(azgaarMapFromSnapshot(snapshot));
  // Source metadata for a pack compiled in the page: there is no file behind it.
  pack.meta.sourceFile = "live world (in-page)";
  return { pack, contentHash, elapsedMs: performance.now() - started };
}

/** Handle one request. Exported so the main-thread fallback runs the same code. */
export function handleRequest(request: CompileRequest): CompileResponse {
  try {
    const { pack, contentHash, elapsedMs } = compileSnapshot(request.snapshot);
    return { id: request.id, ok: true, pack, contentHash, elapsedMs };
  } catch (error) {
    return { id: request.id, ok: false, error: (error as Error).message };
  }
}

/**
 * The worker's source, as a string.
 *
 * Keeping it a blob is what lets the product stay a single module: the "one
 * module" rule survives a Worker being introduced.
 *
 * The handshake is the subtle part. `import()` is asynchronous, so a message can
 * arrive *before* the engine exists — and then the first compile of every session
 * fails with "engine not loaded". So the worker queues anything that arrives
 * early and flushes it once the import resolves. (Browsers also buffer messages
 * sent to a worker with no listener, but relying on that is exactly the kind of
 * implicit behaviour that breaks on a different engine.)
 */
export function compileWorkerSource(modUrl: string): string {
  return `// OpenConquest compile worker — generated by openconquest/engine/compile/worker-protocol.ts
const pending = [];
let api = null;

function handle(request) {
  if (!api) {
    // The import has not resolved yet; run it as soon as it has.
    pending.push(request);
    return;
  }
  self.postMessage(api.handleCompileRequest(request));
}

self.onmessage = (event) => handle(event.data);

import(${JSON.stringify(modUrl)})
  .then(() => {
    api = self.TotalWar && self.TotalWar.engine;
    if (!api) {
      const reason = "the mod loaded in this worker but exposed no engine";
      for (const request of pending.splice(0)) {
        self.postMessage({ id: request.id, ok: false, error: reason });
      }
      return;
    }
    for (const request of pending.splice(0)) handle(request);
  })
  .catch((error) => {
    const reason = "the mod could not be imported in this worker: " + (error && error.message ? error.message : error);
    for (const request of pending.splice(0)) self.postMessage({ id: request.id, ok: false, error: reason });
  });
`;
}
